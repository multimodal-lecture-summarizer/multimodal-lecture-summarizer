import datetime
from typing import List, Dict, Any
from pydantic import Field
from app.schemas.base import CamelModel


class SystemStatDTO(CamelModel):
    stat_id: int = Field(..., description="Unique statistic entry ID")
    date: datetime.date = Field(..., description="The date for the recorded statistics")
    total_users: int = Field(
        ..., description="Total cumulative registered users up to this date"
    )
    new_users: int = Field(
        ..., description="Number of new users registered on this day"
    )
    total_videos_processed: int = Field(
        ..., description="Number of videos successfully summarized on this day"
    )
    total_jobs_run: int = Field(
        ..., description="Total number of jobs executed (including failures)"
    )


class ResourceCostStats(CamelModel):
    estimated_api_cost: float = Field(
        ..., description="Estimated Groq and Whisper API costs in USD"
    )
    total_processing_time_seconds: float = Field(
        ..., description="Total processing latency in seconds across all videos"
    )
    gpu_hours: float = Field(..., description="Estimated GPU hours consumed")


class JobStatusDistribution(CamelModel):
    status: str = Field(..., description="The job status label")
    count: int = Field(..., description="The number of jobs with this status")


class WeeklyVideoVolume(CamelModel):
    week_label: str = Field(..., description="The label for the week, e.g., Tuần 1, Tuần 2")
    count: int = Field(..., description="Number of videos processed in this week")


class ModelUsageDistribution(CamelModel):
    model_name: str = Field(..., description="The name of the LLM model used")
    percentage: float = Field(..., description="Percentage of summaries generated by this model")
    count: int = Field(..., description="Number of summaries generated by this model")


class AdminDashboardStats(CamelModel):
    history: List[SystemStatDTO] = Field(
        default=[], description="Historical stats trend"
    )
    job_distribution: List[JobStatusDistribution] = Field(
        default=[], description="Overview of job success/failure rates"
    )
    resource_usage: ResourceCostStats = Field(
        ..., description="Estimated system resource and API cost metrics"
    )
    weekly_volume: List[WeeklyVideoVolume] = Field(
        default=[], description="Video processed volume in the last 6 weeks"
    )
    model_distribution: List[ModelUsageDistribution] = Field(
        default=[], description="LLM model usage percentage breakdown"
    )


class PerformanceSummaryDTO(CamelModel):
    avg_rtf: float = Field(..., description="Average Real-Time Factor (processing_sec / duration_sec)")
    avg_processing_time_sec: float = Field(..., description="Average processing latency in seconds")
    total_processed_hours: float = Field(..., description="Total cumulative video duration in hours")
    total_jobs_evaluated: int = Field(default=0, description="Total completed jobs analyzed")


class ScatterDataPointDTO(CamelModel):
    video_id: str = Field(..., description="Unique video identifier")
    title: str = Field(..., description="Video title or file name")
    duration_sec: float = Field(..., description="Original video duration in seconds")
    processing_sec: float = Field(..., description="Actual processing time in seconds")
    rtf: float = Field(..., description="Real-Time Factor (processing_sec / duration_sec)")
    resolution: str = Field(default="1080p", description="Video resolution e.g. 1080p, 720p")


class DurationBucketDTO(CamelModel):
    bucket: str = Field(..., description="Bucket identifier: short, medium, long")
    label: str = Field(..., description="Display label e.g. < 5 phút, 5 - 15 phút, > 15 phút")
    count: int = Field(..., description="Number of videos in this duration segment")
    avg_duration_sec: float = Field(..., description="Average duration in seconds")
    avg_processing_sec: float = Field(..., description="Average processing time in seconds")
    avg_rtf: float = Field(..., description="Average Real-Time Factor in this bucket")
    success_rate: float = Field(..., description="Job success rate percentage (0 - 100%)")


class PerformanceAnalyticsDTO(CamelModel):
    summary_metrics: PerformanceSummaryDTO = Field(..., description="Global RTF and processing metrics")
    scatter_data: List[ScatterDataPointDTO] = Field(default=[], description="Scatter plot coordinates")
    duration_buckets: List[DurationBucketDTO] = Field(default=[], description="Grouped duration bucket metrics")
